"""C99 code generation for the pod: feature spec, detector config, and the classifier.

Every model is wrapped as   float lyra_model_predict(const float x[LYRA_N_FEATURES])
= Platt(z) with z the backend's raw score. Each emitter also returns a Python replica that
computes exactly what the generated C computes (same float32/float64 operations in the same
order), so Python/C parity is tested against the deployed model, and the deviation of the
deployed model from the scikit-learn/XGBoost original is measured separately.

Backends: RF/ET -> emlearn inline (float features, 8-bit leaf probabilities); XGBoost -> own
exporter from XGBoost's JSON model (m2cgen 0.10 fails on XGBoost 3.x); LR, SVC -> own exporters.
"""

from __future__ import annotations

import json
from importlib.metadata import version

import numpy as np

from . import config as C


def f32(x) -> str:
    """Shortest decimal that round-trips to the same float32."""
    v = np.float32(x)
    if not np.isfinite(v):
        raise ValueError(f"non-finite constant {x}")
    s = np.format_float_positional(v, unique=True, trim="0")
    return (s if any(ch in s for ch in ".e") else s + ".0") + "f"


def f64(x) -> str:
    return repr(float(x))


