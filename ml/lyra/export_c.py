# ---- tree forests via emlearn --------------------------------------------------------------------------


def emlearn_forest(est, cols: list[int], A: float, B: float):
    old = np.geterr()
    try:
        import emlearn
        from emlearn import cgen
        from emlearn.trees import leaves_to_bytelist
    finally:
        np.seterr(**old)  # emlearn.bayes calls numpy.seterr(all='raise') at import time

    conv = emlearn.convert(est, method="inline", dtype="float", leaf_bits=8)
    body = conv.save(name="lyra_forest")
    nodes, roots, leaves = conv.forest_
    thr = np.array([np.float32(float(cgen.constant(n[1], dtype="float")[:-1])) for n in nodes], np.float32)
    feat = np.array([n[0] for n in nodes])
    left = np.array([n[2] for n in nodes])
    right = np.array([n[3] for n in nodes])
    leaf_bytes = np.array(leaves_to_bytelist(leaves, leaf_bits=8), np.uint8)
    n_trees = len(roots)

    def replica_z(X: np.ndarray) -> np.ndarray:
        Z = np.asarray(X, np.float32)[:, cols]
        acc = np.zeros(Z.shape[0], np.float32)
        for root in roots:
            node = np.full(Z.shape[0], root)
            while (inner := node >= 0).any():
                i = np.flatnonzero(inner)
                go_left = Z[i, feat[node[i]]] < thr[node[i]]
                node[i] = np.where(go_left, left[node[i]], right[node[i]])
            leaf = -node - 1
            acc = acc + leaf_bytes[2 * leaf + 1].astype(np.float32) / np.float32(255.0)
        p = acc / np.float32(n_trees)
        return _logit_clip(p)

    code = ("#pragma GCC diagnostic push\n#pragma GCC diagnostic ignored \"-Wunused-parameter\"\n" + body
            + "\n#pragma GCC diagnostic pop\n") + f"""
static float lyra_model_raw(const float *x) {{ /* x: the model's input columns */
    float proba[2];
    lyra_forest_predict_proba(x, {len(cols)}, proba, 2);
    double p = proba[1];
    if (p < 1e-6) p = 1e-6;
    if (p > 1.0 - 1e-6) p = 1.0 - 1e-6;
    return (float)log(p / (1.0 - p));
}}
"""
    meta = {"backend": f"emlearn {version('emlearn')} method=inline dtype=float leaf_bits=8",
            "trees": n_trees, "decision_nodes": len(nodes), "leaves": len(leaves)}
    return code, replica_z, meta


def _logit_clip(p32: np.ndarray) -> np.ndarray:
    p = np.clip(p32.astype(np.float64), 1e-6, 1 - 1e-6)
    return np.log(p / (1.0 - p)).astype(np.float32)


# ---- XGBoost -------------------------------------------------------------------------------------------


def xgb_forest(model, cols: list[int], A: float, B: float):
    raw = json.loads(model.get_booster().save_raw(raw_format="json"))
    gb = raw["learner"]["gradient_booster"]["model"]
    trees = gb["trees"]
    bs = raw["learner"]["learner_model_param"]["base_score"]
    base = float(json.loads(bs)[0]) if bs.startswith("[") else float(bs)
    base_margin = np.float32(np.log(base / (1 - base)))
    feat, thr, left, right, dleft, roots = [], [], [], [], [], []
    for t in trees:
        roots.append(len(feat))
        lc, rc = np.array(t["left_children"]), np.array(t["right_children"])
        sc = np.array(t["split_conditions"], np.float32)
        si = np.array(t["split_indices"])
        dl = np.array(t["default_left"], bool)
        leaf = lc == -1
        feat += np.where(leaf, -1, si).tolist()
        thr += sc.tolist()
        left += np.where(leaf, 0, lc).tolist()
        right += np.where(leaf, 0, rc).tolist()
        dleft += dl.tolist()
    feat_a, thr_a = np.array(feat), np.array(thr, np.float32)
    left_a, right_a, roots_a = np.array(left), np.array(right), np.array(roots)

    def replica_z(X: np.ndarray) -> np.ndarray:
        Z = np.asarray(X, np.float32)[:, cols]
        acc = np.full(Z.shape[0], base_margin, np.float32)
        for r in roots_a:
            node = np.zeros(Z.shape[0], int)
            while (inner := feat_a[r + node] >= 0).any():
                i = np.flatnonzero(inner)
                g = r + node[i]
                node[i] = np.where(Z[i, feat_a[g]] < thr_a[g], left_a[g], right_a[g])
            acc = acc + thr_a[r + node]
        return acc

    arr = lambda ct, nm, xs, fmt: f"static const {ct} {nm}[{len(xs)}] = {{{','.join(fmt(x) for x in xs)}}};\n"  # noqa: E731
    code = (
        arr("int8_t", "lyra_xgb_feature", feat, str) + arr("float", "lyra_xgb_value", thr, f32)
        + arr("uint8_t", "lyra_xgb_left", left, str) + arr("uint8_t", "lyra_xgb_right", right, str)
        + arr("uint16_t", "lyra_xgb_root", roots, str)
        + f"""
/* XGBoost {version('xgboost')} gbtree, {len(trees)} trees: x < split -> left (no missing values: invalid
 * windows never reach the model). value[] holds split conditions for inner nodes, leaf weights for leaves. */
static float lyra_model_raw(const float *x) {{
    float acc = {f32(base_margin)};
    for (int t = 0; t < {len(trees)}; t++) {{
        const int r = lyra_xgb_root[t];
        int n = 0;
        while (lyra_xgb_feature[r + n] >= 0)
            n = (x[lyra_xgb_feature[r + n]] < lyra_xgb_value[r + n]) ? lyra_xgb_left[r + n] : lyra_xgb_right[r + n];
        acc += lyra_xgb_value[r + n];
    }}
    return acc;
}}
"""
    )
    if max(left + right) > 255 or len(feat) > 65535:
        raise ValueError("XGBoost tree too large for uint8 child / uint16 root indices")
    meta = {"backend": f"own exporter from XGBoost {version('xgboost')} JSON model (m2cgen 0.10.0 failed: "
                       "TypeError on XGBoost 3.x base_score)", "trees": len(trees), "nodes": len(feat),
            "base_score": base}
    return code, replica_z, meta


# ---- LR / SVC ------------------------------------------------------------------------------------------


def linear(model, cols: list[int], A: float, B: float):
    sc, lr = model[0], model[-1]
    mu, sd, w, b = sc.mean_, sc.scale_, lr.coef_[0], float(lr.intercept_[0])

    def replica_z(X):
        Z = np.asarray(X, np.float32)[:, cols].astype(np.float64)
        acc = np.full(Z.shape[0], b)
        for i in range(len(cols)):
            acc = acc + w[i] * ((Z[:, i] - mu[i]) / sd[i])
        return acc.astype(np.float32)

    code = (f"static const double lyra_lr_mean[{len(cols)}] = {{{','.join(map(f64, mu))}}};\n"
            f"static const double lyra_lr_scale[{len(cols)}] = {{{','.join(map(f64, sd))}}};\n"
            f"static const double lyra_lr_coef[{len(cols)}] = {{{','.join(map(f64, w))}}};\n"
            f"static float lyra_model_raw(const float *x) {{\n    double acc = {f64(b)};\n"
            f"    for (int i = 0; i < {len(cols)}; i++) acc += lyra_lr_coef[i] * (((double)x[i] - lyra_lr_mean[i]) / lyra_lr_scale[i]);\n"
            f"    return (float)acc;\n}}\n")
    return code, replica_z, {"backend": "own exporter (standardise + linear, double)", "parameters": 3 * len(cols) + 1}


def svc(model, cols: list[int], A: float, B: float):
    sc, sv = model[0], model[-1]
    mu, sd = sc.mean_, sc.scale_
    S, a, b = sv.support_vectors_.astype(np.float32), sv.dual_coef_[0], float(sv.intercept_[0])
    gamma = float(sv._gamma)
    n, d = S.shape

    def replica_z(X):
        Z = ((np.asarray(X, np.float32)[:, cols].astype(np.float64) - mu) / sd)
        out = np.empty(Z.shape[0], np.float32)
        with np.errstate(under="ignore"):  # exp underflow -> 0, as in C
            for s in range(0, Z.shape[0], 4096):
                d2 = ((Z[s:s + 4096, None, :] - S.astype(np.float64)[None]) ** 2).sum(axis=2)
                out[s:s + 4096] = (np.exp(-gamma * d2) @ a + b).astype(np.float32)
        return out

    code = (f"static const double lyra_svc_mean[{d}] = {{{','.join(map(f64, mu))}}};\n"
            f"static const double lyra_svc_scale[{d}] = {{{','.join(map(f64, sd))}}};\n"
            f"static const float lyra_svc_sv[{n * d}] = {{{','.join(map(f32, S.ravel()))}}};\n"
            f"static const float lyra_svc_alpha[{n}] = {{{','.join(map(f32, a))}}};\n"
            f"static float lyra_model_raw(const float *x) {{\n    double z[{d}], acc = {f64(b)};\n"
            f"    for (int i = 0; i < {d}; i++) z[i] = ((double)x[i] - lyra_svc_mean[i]) / lyra_svc_scale[i];\n"
            f"    for (int s = 0; s < {n}; s++) {{\n        double d2 = 0.0;\n"
            f"        for (int i = 0; i < {d}; i++) {{ const double t = z[i] - (double)lyra_svc_sv[s * {d} + i]; d2 += t * t; }}\n"
            f"        acc += (double)lyra_svc_alpha[s] * exp({f64(-gamma)} * d2);\n    }}\n    return (float)acc;\n}}\n")
    return code, replica_z, {"backend": "own exporter (RBF SVC, double kernel)", "support_vectors": n,
                             "parameters": n * d + n + 2 * d + 2}


EMITTERS = {"RF": emlearn_forest, "ET": emlearn_forest, "XGB": xgb_forest, "LR": linear, "SVC": svc}


def model_header(name: str, model, cols: list[int], A: float, B: float, model_id: str):
    if getattr(model, "n_features_in_", len(cols)) != len(cols):
        raise ValueError(f"model expects {model.n_features_in_} inputs, {len(cols)} columns given")
    code, replica_z, meta = EMITTERS[name](model, cols, A, B)
    col_list = ",".join(map(str, cols))
    hdr = f"""/* {model_id}: generated by ml/lyra/export_c.py. Do not edit.
 * Experimental research component: not clinically validated, not a diagnostic device.
 * Classifier: {name} ({meta['backend']}); inputs: LYRA_N_FEATURES features in lyra_feature_spec.h order;
 * output: calibrated probability of a target convulsive-seizure window (Platt: 1/(1+exp(-(A z + B)))).
 */
#ifndef LYRA_MODEL_H
#define LYRA_MODEL_H

#include <math.h>
#include <stdint.h>

#include "lyra_feature_spec.h"

#define LYRA_MODEL_N_INPUTS {len(cols)}
static const uint8_t lyra_model_columns[LYRA_MODEL_N_INPUTS] = {{{col_list}}};
#define LYRA_CALIB_A {f64(A)}
#define LYRA_CALIB_B {f64(B)}

{code}
static float lyra_model_predict(const float features[LYRA_N_FEATURES]) {{
    float x[LYRA_MODEL_N_INPUTS];
    for (int i = 0; i < LYRA_MODEL_N_INPUTS; i++) x[i] = features[lyra_model_columns[i]];
    const double z = (double)lyra_model_raw(x);
    return (float)(1.0 / (1.0 + exp(-(LYRA_CALIB_A * z + LYRA_CALIB_B))));
}}

#endif
"""

    def replica_prob(X: np.ndarray) -> np.ndarray:
        z = replica_z(X).astype(np.float64)
        return (1.0 / (1.0 + np.exp(-(A * z + B)))).astype(np.float32)

    return hdr, replica_prob, meta


