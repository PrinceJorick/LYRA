"""Stage 4: export the frozen multimodal and SIMULATED_ENV-only random forests to C99.

Converter: m2cgen (exact double-precision leaf probabilities). emlearn 0.23.2 was evaluated first
and rejected for this export: it stores leaf probabilities in 8 bits (leaf_bits=8), which cannot
meet the required max |p_C - p_sklearn| < 1e-5. The wrapper takes float features and widens them
to double, which mirrors scikit-learn's float32 cast of its inputs, so tree decisions match.
Writes mlm/export/c99/ (lyra_<track>_rf.c/.h, export_manifest.json).
Usage: python scripts/export_c99.py
"""

import json
from pathlib import Path

import joblib
import m2cgen

from train_stage4 import MODELS, sha256

OUT = Path(__file__).resolve().parents[1] / "export" / "c99"
EXPORTED = ("multimodal", "simenv")

HEADER = """/* {name}: LYRA {track} random forest, generated by scripts/export_c99.py (m2cgen {m2c}).
 * EXPERIMENTAL research model trained on SeizeIT2 Train/CV (sub-001..sub-096); not a medical device.
 * Output is a window score for the event-confirmation logic, never a diagnosis.
 * Feature order (must match the pod's feature extraction exactly):
{features} */
#ifndef {guard}
#define {guard}

#define {macro}_N_FEATURES {n}

/* proba_out[0] = P(not event-like), proba_out[1] = P(event-like). Returns 0, or -1 on a wrong length. */
int {name}_predict(const float *features, int n_features, double proba_out[2]);

#endif
"""

WRAPPER = """
int {name}_predict(const float *features, int n_features, double proba_out[2]) {{
    double x[{n}];
    int i;
    if (n_features != {n}) {{
        return -1;
    }}
    for (i = 0; i < {n}; ++i) {{
        x[i] = (double)features[i];
    }}
    {name}_score(x, proba_out);
    return 0;
}}
"""


def export(track: str, meta: dict) -> dict:
    path = MODELS / meta["file"]
    if sha256(path) != meta["sha256"]:
        raise SystemExit(f"{path.name} does not match its frozen sha256")
    model, name = joblib.load(path), f"lyra_{track}_rf"
    n, feats = len(meta["feature_names"]), meta["feature_names"]
    code = m2cgen.export_to_c(model, function_name=f"{name}_score")
    for helper in ("add_vectors", "mul_vector_number"):  # file-local, so two models can link together
        code = code.replace(f"void {helper}(", f"static void {helper}(")
    code = code.replace(f"void {name}_score(", f"static void {name}_score(")
    c = OUT / f"{name}.c"
    h = OUT / f"{name}.h"
    h.write_text(HEADER.format(name=name, track=track, m2c=m2cgen.__version__, guard=name.upper() + "_H",
                               macro=name.upper(), n=n, features="\n".join(f" *   [{i:2d}] {f}" for i, f in enumerate(feats))))
    c.write_text(f'#include "{h.name}"\n' + code + WRAPPER.format(name=name, n=n))
    return {"model_file": meta["file"], "model_sha256": meta["sha256"], "function": f"{name}_predict",
            "feature_names": feats, "files": {f.name: sha256(f) for f in (c, h)}}


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    pipe = json.loads((MODELS / "frozen_pipeline.json").read_text())
    manifest = {"converter": "m2cgen", "converter_version": m2cgen.__version__, "c_standard": "C99",
                "emlearn_rejected": "emlearn 0.23.2 quantizes leaf probabilities to 8 bits (leaf_bits=8); "
                                    "required max_abs_diff < 1e-5 is not reachable",
                "input": "float features, widened to double (matches scikit-learn's float32 input cast)",
                "pipeline_commit": pipe["git_commit"], "confirmation": pipe["confirmation"],
                "operating_points": pipe["operating_points"],
                "models": {t: export(t, pipe["models"][t]) for t in EXPORTED}}
    (OUT / "export_manifest.json").write_text(json.dumps(manifest, indent=1))
    print(json.dumps({t: m["files"] for t, m in manifest["models"].items()}, indent=1))


if __name__ == "__main__":
    main()
